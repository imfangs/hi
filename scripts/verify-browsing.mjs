#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const args = Object.fromEntries(process.argv.slice(2).reduce((rows, value, i, all) => i % 2 === 0 ? [...rows, [value.replace(/^--/, ''), all[i + 1]]] : rows, []));
assert(args.url && args.out && args['playwright-root'], 'Use --url ORIGIN --out DIRECTORY --playwright-root EXISTING_PROJECT');
const base = new URL(args.url);
assert(['http:', 'https:'].includes(base.protocol) && base.pathname === '/', 'Provide an HTTP(S) origin');
const { chromium } = createRequire(path.resolve(args['playwright-root'], 'package.json'))('playwright');
const out = path.resolve(args.out);
fs.mkdirSync(out, { recursive: true });
const report = { startedAt: new Date().toISOString(), base: base.origin, results: [], errors: [], limits: ['Browser viewports, not physical phones.', 'No authenticated product actions or message sends.', 'Behavior and layout checks do not establish reader preference or conversion.'] };
const save = () => fs.writeFileSync(path.join(out, 'browsing.json'), JSON.stringify(report, null, 2) + '\n');
const browser = await chromium.launch({ headless: true });
let step = 'start';
const waitCount = (page, n) => page.waitForFunction(n => [...document.querySelectorAll('.work-item')].filter(x => !x.hidden).length === n, n);
async function ready(page, url) { await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 }); await page.waitForFunction(() => !document.querySelector('.browse-toolbar')?.hidden); }
async function layout(page) { assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'horizontal overflow'); }
try {
    for (const view of [{ name: 'desktop', width: 1440, height: 1000, colorScheme: 'light' }, { name: 'phone', width: 390, height: 844, colorScheme: 'light' }, { name: 'narrow-dark', width: 320, height: 740, colorScheme: 'dark' }]) {
        const context = await browser.newContext({ viewport: { width: view.width, height: view.height }, colorScheme: view.colorScheme, reducedMotion: 'reduce' });
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', e => errors.push(e.message));
        step = `${view.name}: overview`;
        console.log(step);
        await ready(page, base.href);
        await waitCount(page, 17);
        await layout(page);
        assert.equal(await page.locator('a a').count(), 0, 'nested anchors');
        assert.equal(await page.locator('.work-launch').count(), 15);
        step = `${view.name}: search`;
        await page.keyboard.press('/');
        assert.equal(await page.locator('#work-search').evaluate(x => x === document.activeElement), true);
        await page.locator('#work-search').fill('花纸');
        await waitCount(page, 1);
        assert.equal(await page.locator('.work-item:visible [data-project]').getAttribute('data-project'), 'chenchen-atelier');
        await page.locator('[data-filter="apps"]').click();
        await waitCount(page, 0);
        assert.equal(await page.locator('.work-empty').isVisible(), true);
        await page.locator('[data-reset-gallery]').click();
        await waitCount(page, 17);
        await page.locator('#work-search').fill('Ｐｏｃｋｅｔ　ＧＥＤ');
        await waitCount(page, 1);
        assert.equal(await page.locator('.work-item:visible [data-project]').getAttribute('data-project'), 'pocket-ged');
        await page.keyboard.press('Escape');
        await waitCount(page, 17);
        await page.locator('#work-search').fill('focus');
        await waitCount(page, 1);
        assert.equal(await page.locator('.work-item:visible [data-project]').getAttribute('data-project'), 'pocofocus');
        await page.locator('.search-clear').click();
        await waitCount(page, 17);
        await page.locator('#work-search').fill('<img src=x onerror=alert(1)>');
        await waitCount(page, 0);
        assert.equal(await page.locator('.work-empty img').count(), 0);
        assert((await page.locator('[data-empty-title]').innerText()).includes('<img'));
        await page.locator('[data-reset-gallery]').click();
        await waitCount(page, 17);
        await page.locator('#work-search').dispatchEvent('compositionstart');
        await page.locator('#work-search').fill('花纸');
        assert.equal(new URL(page.url()).searchParams.has('q'), false);
        await page.locator('#work-search').dispatchEvent('compositionend');
        await waitCount(page, 1);
        const queryUrl = page.url();
        await page.reload({ waitUntil: 'domcontentloaded' });
        await waitCount(page, 1);
        assert.equal(await page.locator('#work-search').inputValue(), '花纸');
        assert.equal(page.url(), queryUrl);
        await page.locator('[data-project="chenchen-atelier"]').click();
        await page.waitForURL(u => u.pathname === '/projects/chenchen-atelier/', { waitUntil: 'domcontentloaded' });
        assert.equal(new URL(page.url()).searchParams.get('q'), '花纸');
        await page.waitForFunction(() => document.querySelector('[data-return-label]')?.textContent === '返回搜索结果');
        const related = await page.locator('.detail-related-card').evaluateAll(xs => xs.map(x => ({ href: x.getAttribute('href'), title: x.querySelector('strong')?.textContent })));
        assert.equal(related.length, 2);
        assert(related.every(x => !x.href.includes('chenchen-atelier') && x.href.includes('view=creations') && !x.href.includes('q=')));
        await page.locator('[data-return]').first().click();
        await page.waitForURL(u => u.pathname === '/', { waitUntil: 'domcontentloaded' });
        await waitCount(page, 1);
        await page.waitForFunction(() => document.activeElement?.getAttribute('data-project') === 'chenchen-atelier');
        step = `${view.name}: return restoration`;
        await ready(page, `${base.origin}/?view=apps#works`);
        await waitCount(page, 4);
        const pocket = page.locator('[data-project="pocket-ged"]');
        await pocket.scrollIntoViewIfNeeded();
        const toolbarBefore = await page.locator('.browse-toolbar').boundingBox();
        assert(toolbarBefore.y >= -1 && toolbarBefore.y < view.height, 'filter toolbar unreachable');
        await pocket.click();
        await page.waitForURL(u => u.pathname === '/projects/pocket-ged/', { waitUntil: 'domcontentloaded' });
        await page.waitForFunction(() => document.querySelector('[data-return-label]')?.textContent === '返回应用作品');
        await page.locator('[data-return]').first().click();
        await page.waitForURL(u => u.pathname === '/' && u.hash === '#work-pocket-ged', { waitUntil: 'domcontentloaded' });
        await waitCount(page, 4);
        await page.waitForFunction(() => document.activeElement?.getAttribute('data-project') === 'pocket-ged');
        const position = await page.locator('#work-pocket-ged').boundingBox();
        const toolbar = await page.locator('.browse-toolbar').boundingBox();
        assert(position.y >= toolbar.y + toolbar.height - 1 && position.y < view.height - 100, 'return card is hidden or behind toolbar');
        await layout(page);
        await page.screenshot({ path: path.join(out, `${view.name}-return.png`) });
        step = `${view.name}: history`;
        await page.locator('[data-filter="games"]').click();
        await waitCount(page, 4);
        await page.locator('[data-filter="reading"]').click();
        await waitCount(page, 5);
        await page.goBack({ waitUntil: 'domcontentloaded' });
        await waitCount(page, 4);
        assert.equal(new URL(page.url()).searchParams.get('view'), 'games');
        await page.goForward({ waitUntil: 'domcontentloaded' });
        await waitCount(page, 5);
        const first = page.locator('.work-item:visible [data-project]').first();
        const originalId = await first.getAttribute('data-project');
        await first.click();
        await page.waitForURL(u => u.pathname.startsWith('/projects/'), { waitUntil: 'domcontentloaded' });
        await page.goBack({ waitUntil: 'domcontentloaded' });
        await waitCount(page, 5);
        assert.equal(new URL(page.url()).searchParams.get('view'), 'reading');
        await page.locator(`[data-project="${originalId}"]`).click();
        await page.waitForURL(u => u.pathname.startsWith('/projects/'), { waitUntil: 'domcontentloaded' });
        const currentPath = new URL(page.url()).pathname;
        await page.locator('.detail-related-card').first().click();
        await page.waitForURL(u => u.pathname !== currentPath && u.searchParams.get('view') === 'reading', { waitUntil: 'domcontentloaded' });
        await layout(page);
        step = `${view.name}: theme`;
        await page.locator('.theme-trigger').click();
        await page.locator('[data-theme="dark"]').click();
        assert(await page.locator('html').evaluate(x => x.classList.contains('dark')));
        await page.reload({ waitUntil: 'domcontentloaded' });
        assert(await page.locator('html').evaluate(x => x.classList.contains('dark')));
        await page.locator('.theme-trigger').click();
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('.theme-options').isVisible(), false);
        await page.locator('.theme-trigger').click();
        await page.locator('[data-theme="system"]').click();
        await page.emulateMedia({ colorScheme: 'light' });
        await page.waitForFunction(() => !document.documentElement.classList.contains('dark'));
        await page.emulateMedia({ colorScheme: 'dark' });
        await page.waitForFunction(() => document.documentElement.classList.contains('dark'));
        assert.deepEqual(errors, []);
        report.results.push({ view: view.name, search: true, composition: true, escapedQuery: true, queryReload: true, return: { position, toolbar, focus: 'pocket-ged', group: 'apps' }, history: true, related, theme: true, noOverflow: true, pageErrors: errors });
        await context.close();
        save();
    }
    step = 'intermediate-widths';
    const geometryContext = await browser.newContext();
    const geometryPage = await geometryContext.newPage();
    const widths = [];
    for (const width of [701, 720, 750, 960, 1024]) {
        await geometryPage.setViewportSize({ width, height: 900 });
        await ready(geometryPage, base.href);
        await geometryPage.evaluate(() => document.fonts.ready);
        const geometry = await geometryPage.evaluate(() => { const rect = el => { const r = el.getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom }; }; return { search: rect(document.querySelector('.work-search')), buttons: [...document.querySelectorAll('[data-filter]')].map(rect) }; });
        for (const b of geometry.buttons)
            assert(!(Math.min(b.right, geometry.search.right) > Math.max(b.left, geometry.search.left) && Math.min(b.bottom, geometry.search.bottom) > Math.max(b.top, geometry.search.top)), `Search and filter overlap at ${width}px`);
        await layout(geometryPage);
        widths.push({ width, ...geometry });
    }
    await geometryContext.close();
    report.results.push({ intermediateWidths: widths });
    step = 'no-JavaScript';
    const context = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 390, height: 844 } });
    const page = await context.newPage();
    await page.goto(base.href, { waitUntil: 'domcontentloaded' });
    assert.equal(await page.locator('.work-item:visible').count(), 17);
    assert.equal(await page.locator('.browse-toolbar:visible').count(), 0);
    assert.equal(await page.locator('.work-launch').count(), 15);
    await page.goto(`${base.origin}/projects/pocket-ged/`, { waitUntil: 'domcontentloaded' });
    assert.equal(await page.locator('[data-return]').first().getAttribute('href'), '/#work-pocket-ged');
    assert.equal(await page.locator('.detail-related-card').count(), 2);
    await context.close();
    report.results.push({ noJavaScript: true, works: 17, directLinks: 15, returnAnchor: true });
    report.passed = true;
}
catch (error) {
    report.passed = false;
    report.errors.push({ step, error: error.stack || String(error) });
    process.exitCode = 1;
}
finally {
    await browser.close();
    report.finishedAt = new Date().toISOString();
    save();
    console.log(JSON.stringify({ passed: report.passed, step, results: report.results.length, errors: report.errors, out }));
}
